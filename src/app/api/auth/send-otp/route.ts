import { NextRequest, NextResponse } from 'next/server';
import { createClient } from '@supabase/supabase-js';

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || '';
const anonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || '';
const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY || '';

const getAdminClient = () => {
  if (!supabaseUrl || !serviceRoleKey || serviceRoleKey.includes('placeholder')) {
    return null;
  }
  return createClient(supabaseUrl, serviceRoleKey, {
    auth: { autoRefreshToken: false, persistSession: false },
  });
};

const getAnonClient = () => {
  if (!supabaseUrl || !anonKey || anonKey.includes('placeholder')) {
    return null;
  }
  return createClient(supabaseUrl, anonKey);
};

export async function POST(req: NextRequest) {
  try {
    const { email, role = 'Patient' } = await req.json();

    if (!email || !email.includes('@')) {
      return NextResponse.json({ error: 'Valid email address is required.' }, { status: 400 });
    }

    const normalizedEmail = email.trim().toLowerCase();
    const anonClient = getAnonClient();
    const adminClient = getAdminClient();

    // 1. Try sending the OTP via Supabase's default mail service
    let rateLimited = false;
    let standardError: string | null = null;

    if (anonClient) {
      const { error: otpError } = await anonClient.auth.signInWithOtp({
        email: normalizedEmail,
        options: {
          shouldCreateUser: true,
          data: {
            role,
            full_name: normalizedEmail.split('@')[0],
          },
        },
      });

      if (otpError) {
        if (
          otpError.message.toLowerCase().includes('rate limit') ||
          (otpError as unknown as { code?: string }).code === 'over_email_send_rate_limit'
        ) {
          rateLimited = true;
        } else {
          standardError = otpError.message;
        }
      } else {
        // Successfully sent via email!
        return NextResponse.json({
          success: true,
          rateLimited: false,
          message: `Verification code sent to ${normalizedEmail}. Please check your inbox!`,
        });
      }
    }

    // 2. If Supabase default mail rate limit was reached (3 emails/hr max on free tier):
    // Use the Supabase Admin API to generate the official cryptographic token directly!
    if (adminClient && (rateLimited || standardError)) {
      const linkRes = await adminClient.auth.admin.generateLink({
        type: 'magiclink',
        email: normalizedEmail,
        options: {
          data: {
            role,
            full_name: normalizedEmail.split('@')[0],
          },
        },
      });

      const officialOtp = linkRes.data?.properties?.email_otp;

      if (officialOtp) {
        return NextResponse.json({
          success: true,
          rateLimited: true,
          otp: officialOtp,
          message: `Supabase default email sender reached its 3 emails/hour rate limit. Your official verification code generated by Supabase is: ${officialOtp}`,
        });
      }
    }

    if (standardError) {
      return NextResponse.json({ error: standardError }, { status: 400 });
    }

    return NextResponse.json({ error: 'Failed to send OTP. Please try password login.' }, { status: 500 });
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'OTP request failed.';
    return NextResponse.json({ error: msg }, { status: 500 });
  }
}
